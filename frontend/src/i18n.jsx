const I18nContext = createContext(null);

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    const saved = localStorage.getItem(LANG_KEY);
    return saved === "hi" || saved === "en" ? saved : "en";
  });

  useEffect(() => {
    document.documentElement.lang = lang;
    localStorage.setItem(LANG_KEY, lang);
  }, [lang]);

  const t = useCallback(
    (key, vars) => {
      let s = dict[lang][key] ?? dict.en[key] ?? key;
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
      return s;
    },
    [lang],
  );

  /** pick(service, "name") -> service.name_hi or service.name_en */
  const pick = useCallback((obj, base) => obj?.[`${base}_${lang}`] || obj?.[`${base}_en`] || "", [lang]);

  const value = useMemo(() => ({ lang, setLang: setLangState, t, pick }), [lang, t, pick]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);

export function formatDate(iso, lang, withTime = true) {
  if (!iso) return "";
  const opts = { dateStyle: "medium", timeZone: "Asia/Kolkata" };
  if (withTime) opts.timeStyle = "short";
  return new Intl.DateTimeFormat(lang === "hi" ? "hi-IN" : "en-IN", opts).format(new Date(iso));
}

/** For plain YYYY-MM-DD values (journey dates, DOB) */
export function formatDay(ymd, lang) {
  if (!ymd) return "";
  const [y, m, d] = ymd.split("-").map(Number);
  return new Intl.DateTimeFormat(lang === "hi" ? "hi-IN" : "en-IN", { dateStyle: "medium", timeZone: "UTC" }).format(
    new Date(Date.UTC(y, m - 1, d)),
  );
}

